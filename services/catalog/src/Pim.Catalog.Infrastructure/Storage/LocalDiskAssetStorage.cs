using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using Pim.Catalog.Application.AssetLibrary;

namespace Pim.Catalog.Infrastructure.Storage;

public sealed class LocalDiskStorageOptions
{
    public const string SectionName = "Assets:LocalDisk";

    /// <summary>
    /// Where binaries are written.
    ///
    /// Defaults OUTSIDE the repository and outside ~/Documents, deliberately.
    /// The repository lives in iCloud (R-1), which has already produced
    /// conflict copies inside `.git/` and `node_modules/`; pointing an asset
    /// store at a synced folder would hand iCloud a few gigabytes of binaries
    /// to duplicate.
    /// </summary>
    public string Root { get; set; } =
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), "pim-asset-store");
}

/// <summary>
/// Binaries on the local filesystem.
///
/// The first implementation of <see cref="IAssetStorage"/>, and deliberately
/// the simplest one that is actually correct. S3 or Azure Blob is a second
/// class implementing the same three methods plus a connection string; nothing
/// above this line changes (decision 2026-08-19).
///
/// Keys are generated by the ingest handler and are content-addressed
/// (`ab/abcdef.../original.jpg`). Nothing a caller sends becomes part of a
/// path. The guard below is therefore belt and braces rather than the only
/// defence — but a path check that only runs when someone has already made a
/// mistake is exactly the one worth having.
/// </summary>
public sealed partial class LocalDiskAssetStorage : IAssetStorage
{
    private readonly string _root;
    private readonly ILogger<LocalDiskAssetStorage> _logger;

    public LocalDiskAssetStorage(
        IOptions<LocalDiskStorageOptions> options,
        ILogger<LocalDiskAssetStorage> logger)
    {
        ArgumentNullException.ThrowIfNull(options);
        _logger = logger ?? throw new ArgumentNullException(nameof(logger));

        _root = Path.GetFullPath(options.Value.Root);
        Directory.CreateDirectory(_root);

        LogRoot(_logger, _root);
    }

    public string ProviderName => "local";

    public async Task SaveAsync(string key, Stream content, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);

        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        // Write to a sibling temp file and move into place. A crash mid-write
        // then leaves no half-file at the real key — which matters because the
        // key is a checksum, so a truncated file would masquerade as the
        // verified content of that hash for ever.
        var temp = path + ".partial";

        await using (var destination = new FileStream(
            temp, FileMode.Create, FileAccess.Write, FileShare.None,
            bufferSize: 81920, useAsync: true))
        {
            await content.CopyToAsync(destination, cancellationToken);
        }

        File.Move(temp, path, overwrite: true);
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken)
    {
        var path = Resolve(key);

        if (!File.Exists(path))
        {
            return Task.FromResult<Stream?>(null);
        }

        Stream stream = new FileStream(
            path, FileMode.Open, FileAccess.Read, FileShare.Read,
            bufferSize: 81920, useAsync: true);

        return Task.FromResult<Stream?>(stream);
    }

    public Task<bool> ExistsAsync(string key, CancellationToken cancellationToken) =>
        Task.FromResult(File.Exists(Resolve(key)));

    [LoggerMessage(EventId = 7220, Level = LogLevel.Information,
        Message = "Asset binaries are stored under {Root}.")]
    private static partial void LogRoot(ILogger logger, string root);

    [LoggerMessage(EventId = 7221, Level = LogLevel.Warning,
        Message = "Rejected an asset key that resolves outside the store root: {Key}")]
    private static partial void LogRejectedKey(ILogger logger, string key);

    /// <summary>
    /// Key to absolute path, refusing anything that escapes the root.
    ///
    /// The comparison is on the RESOLVED path rather than on the key's text:
    /// checking for ".." in a string is the version of this that keeps getting
    /// bypassed, because "%2e%2e", symlinks and unicode all spell it
    /// differently. GetFullPath normalises first, then the answer is a simple
    /// prefix test.
    /// </summary>
    private string Resolve(string key)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(key);

        var combined = Path.GetFullPath(Path.Combine(_root, key));

        if (!combined.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal)
            && !string.Equals(combined, _root, StringComparison.Ordinal))
        {
            LogRejectedKey(_logger, key);
            throw new UnauthorizedAccessException($"Asset key '{key}' resolves outside the store root.");
        }

        return combined;
    }
}
